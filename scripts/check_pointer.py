#!/usr/bin/env python3
"""Gate 2: metamodel-pointer.yaml is present and internally consistent.

The pointer is regenerated by the OpenDEAM root-model fan-out and is never
hand-edited. This gate therefore does not rewrite it: it asserts that the
pointer declares the fields the allocation validator and the human reader both
rely on, and that the identity and repository values match what
docs/FOUNDATIONS.md section 5 records as the allocation.

A finding here means the pointer drifted from its allocation. Fix the
allocation in dea-architecture-framework, not this file.
"""

from __future__ import annotations

import sys
from pathlib import Path

import yaml

REPO = Path(__file__).resolve().parent.parent

REQUIRED_METAMODEL_FIELDS = (
    "version",
    "entity_id",
    "class_alias",
    "layer",
    "building_block",
    "status",
    "viewer_url",
)
REQUIRED_CATALOG_FIELDS = ("name", "repo", "status", "rename")

EXPECTED_CLASS_ALIAS = "ISS"
EXPECTED_ENTITY_ID = "dea:entity-information-system-service"
EXPECTED_REPO = "technehub-labs/dea-catalog-information-system-services"
EXPECTED_RENAME_STATUS = "not-required"


def main() -> int:
    path = REPO / "metamodel-pointer.yaml"
    if not path.exists():
        print("FAIL: metamodel-pointer.yaml is missing")
        return 1

    try:
        doc = yaml.safe_load(path.read_text(encoding="utf-8")) or {}
    except Exception as exc:
        print(f"FAIL: metamodel-pointer.yaml does not parse: {exc}")
        return 1

    metamodel = doc.get("metamodel") or {}
    catalog = doc.get("catalog") or {}
    rename = catalog.get("rename") or {}

    findings: list[str] = []

    for field in REQUIRED_METAMODEL_FIELDS:
        if metamodel.get(field) in (None, ""):
            findings.append(f"metamodel.{field} is missing or empty")
    for field in REQUIRED_CATALOG_FIELDS:
        if catalog.get(field) in (None, ""):
            findings.append(f"catalog.{field} is missing or empty")

    if metamodel.get("class_alias") != EXPECTED_CLASS_ALIAS:
        findings.append(
            f"metamodel.class_alias is {metamodel.get('class_alias')!r}, "
            f"expected {EXPECTED_CLASS_ALIAS!r}"
        )
    if metamodel.get("entity_id") != EXPECTED_ENTITY_ID:
        findings.append(
            f"metamodel.entity_id is {metamodel.get('entity_id')!r}, "
            f"expected {EXPECTED_ENTITY_ID!r}"
        )
    if catalog.get("repo") != EXPECTED_REPO:
        findings.append(f"catalog.repo is {catalog.get('repo')!r}, expected {EXPECTED_REPO!r}")
    if rename.get("status") != EXPECTED_RENAME_STATUS:
        findings.append(
            f"catalog.rename.status is {rename.get('status')!r}, "
            f"expected {EXPECTED_RENAME_STATUS!r}"
        )

    print()
    if findings:
        print("Pointer findings:")
        for f in findings:
            print(f"  - {f}")
    print(f"Pointer checked. Findings: {len(findings)}")
    return 1 if findings else 0


if __name__ == "__main__":
    sys.exit(main())